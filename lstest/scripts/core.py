class StopSupervisor:
    def __init__(self, stop_file: Path, *, disk_limit_bytes: int = 1024**3):
        self.stop_file = stop_file
        self.disk_limit_bytes = disk_limit_bytes
        self._event = threading.Event()
        self.reason = ""

    def request(self, reason: str = "requested") -> None:
        self.reason = reason
        self._event.set()

    @property
    def requested(self) -> bool:
        return self._event.is_set() or self.stop_file.is_file()

    def disk_ok(self, path: Path) -> bool:
        try:
            return path.stat().st_size >= 0 and shutil.disk_usage(path).free > self.disk_limit_bytes
        except OSError:
            return False

    def check(self, path: Path | None = None) -> str | None:
        """返回停止原因；磁盘低于停止线时阻止新的用例。"""
        if self.stop_file.is_file():
            return self.reason or "STOP_FILE"
        if path is not None and not self.disk_ok(path):
            self.request("DISK_STOP_LINE")
            return self.reason
        return self.reason if self.requested else None

    def wait(self, seconds: float, *, tick: float = 0.1, path: Path | None = None) -> str | None:
        """可中断、有上限的等待；永不向 time.sleep 传递负数。"""
        duration = max(0.0, float(seconds))
        deadline = time.monotonic() + duration
        while True:
            reason = self.check(path)
            if reason:
                return reason
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                return None
            self._event.wait(min(max(0.01, tick), remaining))

    def raise_if_requested(self, path: Path | None = None) -> None:
        reason = self.check(path)
        if reason:
            raise RuntimeError(reason)


class StopPolicy:
    """The only task-level stop gate.

    A case failure, parser failure, device error, recovery exhaustion, or a
    callback exception is deliberately *not* a task stop.  These conditions
    stay visible in the current case and the supervisor continues with the
    next runnable case.  The small whitelist below reflects conditions where
    continuing would make the evidence untrustworthy or unsafe.
    """

    ALLOWED = frozenset({
        "USER_STOP",
        "EVIDENCE_WRITE_FAILURE",
        "BLOCKED_PROFILE_CONTRACT",
        "INFRASTRUCTURE_UNAVAILABLE",
        "PROFILE_SAFETY_STOP",
        "DISK_STOP_LINE",
    })

    def __init__(self, stop: StopSupervisor) -> None:
        self.stop = stop
        self.records: list[dict[str, Any]] = []

    def request(self, code: str, *, reason: str = "", **details: Any) -> bool:
        normalized = str(code or "").strip().upper()
        if normalized not in self.ALLOWED:
            return False
        self.records.append({"code": normalized, "reason": reason, "details": dict(details), "at": now_iso()})
        self.stop.request(normalized)
        return True

    def check(self, path: Path) -> str | None:
        raw = self.stop.check(path)
        if not raw:
            return None
        if raw in {"STOP_FILE", "requested"}:
            self.request("USER_STOP", reason="用户请求停止")
            return "USER_STOP"
        if raw == "DISK_STOP_LINE":
            self.request("DISK_STOP_LINE", reason="标准证据存储空间不足")
            return "DISK_STOP_LINE"
        return raw if raw in self.ALLOWED else None


class TaskSupervisor:
    """Contain ordinary action/case exceptions so a stress task can continue."""

    def __init__(self, artifacts: "TaskArtifacts") -> None:
        self.artifacts = artifacts

    def run(self, case_id: str, phase: str, action: Any, fallback: Any = None) -> Any:
        try:
            return action()
        except Exception as error:
            self.artifacts.record_anomaly(
                "TOOL_ACTION_EXCEPTION",
                "工具动作异常，当前轮将继续收尾。",
                case_id=case_id,
                phase=phase,
                error=f"{type(error).__name__}: {error}",
                handling="记录异常并继续当前轮",
            )
            return fallback


class TaskArtifacts:
    """The four-artifact result ledger used by every new lstest task.

    ``serial_logs/`` is the continuous device-side fact source.  ``tool.log``
    is the single human-readable execution ledger.  ``results.csv`` contains
    one final row per logical case, and ``cases.csv`` freezes the input order
    before any device action.  No derived JSON, per-tool log, or summary file
    is created for new tasks.
    """

    TOOL_FIELDS = (
        "time", "level", "event", "task_id", "epoch", "round", "case_id",
        "phase", "source", "device", "port_role", "action_id", "broadcast_id",
        "correlation_id", "status", "reason", "attempt", "max_attempts",
        "elapsed_ms", "rule_id", "expected", "actual", "raw", "normalized",
        "handling", "evidence", "message", "details",
    )
    RESULT_FIELDS = (
        "round", "case_id", "started_at", "ended_at", "epoch", "scenario",
        "input_text", "audio_file", "audio_sha256", "profile_version", "profile_sha256",
        "raw_fact_counts", "logical_fact_counts", "association", "anomaly_codes",
        "primary_reason", "raw_status", "reviewed_status", "final_status", "reason",
        "evidence", "facts_json",
    )
    CASE_FIELDS = (
        "case_order", "case_id", "scenario", "input_text", "audio_file", "audio_sha256",
        "case_contract", "source_file", "source_sha256", "random_seed",
        "profile_version", "profile_sha256",
    )

    def __init__(
        self,
        result_root: Path,
        task_slug: str,
        detail_fields: Sequence[str] = (),
        *,
        terminal_stream: Any | None = None,
    ):
        stamp = now_dt().strftime("%Y%m%d_%H%M%S")
        base = Path(result_root) / f"{stamp}_{task_slug}"
        candidate = base
        suffix = 1
        while candidate.exists():
            candidate = Path(f"{base}_{suffix:02d}")
            suffix += 1
        self.run_dir = candidate
        (self.run_dir / "serial_logs").mkdir(parents=True, exist_ok=False)
        self.task_id = self.run_dir.name
        self.tool_log_path = self.run_dir / "tool.log"
        self.results_path = self.run_dir / "results.csv"
        self.cases_path = self.run_dir / "cases.csv"
        self.stop = StopSupervisor(self.run_dir / "STOP")
        self.stop_policy = StopPolicy(self.stop)
        self._lock = threading.RLock()
        self._tool = self.tool_log_path.open("a", encoding="utf-8")
        self._terminal_stream: Any | None = terminal_stream
        self._terminal_mirror_failure_recorded = False
        self._legacy_stdout_disabled = False
        self.timeline = TimelineLedger(self._append_timeline_line, now_human)
        result_fields = list(dict.fromkeys([*self.RESULT_FIELDS, *detail_fields]))
        self._csv = self.results_path.open("w", encoding="utf-8-sig", newline="")
        self._writer = csv.DictWriter(self._csv, fieldnames=result_fields, extrasaction="ignore")
        self._writer.writeheader()
        self._csv.flush()
        self._cases = self.cases_path.open("w", encoding="utf-8-sig", newline="")
        self._cases_writer = csv.DictWriter(self._cases, fieldnames=self.CASE_FIELDS, extrasaction="ignore")
        self._cases_writer.writeheader()
        self._cases.flush()
        self._cases_frozen = False
        self._frozen_case_count = 0
        self._planned_case_count = 0
        self._lazy_case_mode = False
        self._lazy_case_identity: dict[str, Any] = {}
        self._declared_case_count = 0
        self._case_positions: dict[str, int] = {}
        self._case_metadata: dict[str, dict[str, Any]] = {}
        self.counts: dict[str, int] = {}
        self.exception_counts: dict[str, int] = {}
        self.anomaly_counts: dict[str, int] = {}
        self.completed_cases = 0
        self.sticky: list[dict[str, Any]] = []
        self.capabilities: dict[str, dict[str, Any]] = {}
        self.checks: dict[str, list[dict[str, Any]]] = {}
        self.current_epoch = 0
        self._epoch_listeners: list[Any] = []
        self.health_policy: dict[str, Any] = {}
        self.health_streaks: dict[str, int] = {}
        self._closers: list[tuple[str, Any]] = []
        self._final_summary: dict[str, Any] | None = None
        self.closed = False
        self.timeline.system(
            f"任务开始: task={task_slug}，结果=serial_logs/、tool.log、results.csv、cases.csv",
            epoch=self.current_epoch,
        )

    def _append_timeline_line(self, line: str) -> None:
        """Write renderer-owned lines atomically and flush them for live review."""
        with self._lock:
            try:
                self._tool.write(line)
                self._tool.flush()
            except OSError as error:
                # The result log is the auditable evidence source.  A failure
                # here means the task cannot safely continue.
                self.stop_policy.request(
                    "EVIDENCE_WRITE_FAILURE",
                    reason="tool.log 无法可靠写入",
                    error=f"{type(error).__name__}: {error}",
                )
                raise
            if self._terminal_stream is not None:
                try:
                    self._terminal_stream.write(line)
                    self._terminal_stream.flush()
                except (OSError, ValueError):
                    # A caller can close or lose its terminal pipe while the
                    # task is still collecting device evidence.  The durable
                    # tool.log remains healthy, so keep the case runnable and
                    # record this once without recursively using Timeline.
                    self._terminal_stream = None
                    if not self._terminal_mirror_failure_recorded:
                        self._terminal_mirror_failure_recorded = True
                        self._tool.write(
                            f"{now_human()} [SYSTEM] 终端镜像不可用，后续过程仅写入 tool.log。\n"
                        )
                        self._tool.flush()

    def enable_terminal_mirror(self, stream: Any | None = None) -> None:
        """Mirror exact human-timeline bytes to one terminal stream.

        Only the timeline writer invokes this mirror, so project adapters cannot
        create terminal-only human entries that differ from the tool log.
        """
        self._terminal_stream = stream or sys.stdout

    def _timeline_contract(self, case_id: str) -> dict[str, Any]:
        metadata = self._case_metadata.get(str(case_id), {})
        configured = metadata.get("timeline", {})
        timeline = dict(configured) if isinstance(configured, Mapping) else {}
        expected: set[str] = {str(item).upper() for item in timeline.get("required_facts", ())}
        return {
            "expected_keys": expected,
            "mirror_policy": dict(timeline.get("mirror_policy", {})) if isinstance(timeline.get("mirror_policy", {}), Mapping) else {},
            "mirror_window_ms": int(timeline.get("mirror_window_ms", 120) or 120),
            "reason_labels": dict(timeline.get("reason_labels", {})) if isinstance(timeline.get("reason_labels", {}), Mapping) else {},
            "duplicate_policy": dict(timeline.get("duplicate_policy", {})) if isinstance(timeline.get("duplicate_policy", {}), Mapping) else {},
        }

    def timeline_case_start(self, case_id: str, *, epoch: int | None = None) -> None:
        metadata = self.case_metadata(case_id)
        contract = self._timeline_contract(case_id)
        self.timeline.start_case(
            case_id,
            epoch=self.current_epoch if epoch is None else int(epoch),
            position=self._case_positions.get(case_id, self.completed_cases + 1),
            total=self._planned_case_count or self._frozen_case_count,
            scenario=str(metadata.get("scenario", "")),
            text=str(metadata.get("input_text", "")),
            **contract,
        )

    def timeline_action(self, case_id: str, *, text: str, audio_file: Any, phase: str = "command") -> None:
        self.timeline.action(case_id, text, audio_file, phase=phase)

    def timeline_action_end(
        self,
        case_id: str,
        *,
        text: str,
        audio_file: Any,
        status: str,
        duration_ms: int | None = None,
    ) -> None:
        self.timeline.action_end(
            case_id,
            text,
            audio_file,
            status=status,
            duration_ms=duration_ms,
        )

    def timeline_wait(self, case_id: str, *, action: str, planned_ms: int) -> None:
        self.timeline.wait(case_id, action, planned_ms=planned_ms)

    def timeline_fact(self, case_id: str, key: str, value: Any, **fields: Any) -> Any:
        return self.timeline.fact(case_id, key, value, epoch=int(fields.pop("epoch", self.current_epoch)), **fields)

    def timeline_player(self, case_id: str, state: Any, **fields: Any) -> None:
        self.timeline.player(case_id, state, epoch=int(fields.pop("epoch", self.current_epoch)), **fields)

    @staticmethod
    def _text(value: Any) -> str:
        if value is None or value == "":
            return "-"
        if isinstance(value, str):
            return value.replace("\r\n", "\\n").replace("\n", "\\n")
        if isinstance(value, (Mapping, list, tuple, set)):
            return json.dumps(value, ensure_ascii=False, sort_keys=True, default=str)
        return str(value)

    def _tool_block(self, event: str, level: str, message: str, fields: Mapping[str, Any]) -> str:
        values = dict(fields)
        port = values.pop("port", "")
        role = values.pop("role", "")
        port_role = values.pop("port_role", "") or "/".join(item for item in (str(port), str(role)) if item)
        evidence = values.pop("evidence", values.pop("evidence_refs", ""))
        raw = values.pop("raw", values.pop("raw_tags", values.pop("raw_line", "")))
        normalized = values.pop("normalized", "")
        expected = values.pop("expected", "")
        actual = values.pop("actual", "")
        known = {
            "time": now_human(),
            "level": level.upper(),
            "event": event,
            "task_id": self.task_id,
            "epoch": values.pop("epoch", self.current_epoch),
            "round": values.pop("round", values.pop("completed_cases", "")),
            "case_id": values.pop("case_id", ""),
            "phase": values.pop("phase", ""),
            "source": values.pop("source", ""),
            "device": values.pop("device", ""),
            "port_role": port_role,
            "action_id": values.pop("action_id", ""),
            "broadcast_id": values.pop("broadcast_id", ""),
            "correlation_id": values.pop("correlation_id", values.pop("query_id", values.pop("request_id", ""))),
            "status": values.pop("status", values.pop("tool_status", "")),
            "reason": values.pop("reason", values.pop("tool_reason", "")),
            "attempt": values.pop("attempt", ""),
            "max_attempts": values.pop("max_attempts", ""),
            "elapsed_ms": values.pop("elapsed_ms", values.pop("duration_ms", "")),
            "rule_id": values.pop("rule_id", ""),
            "expected": expected,
            "actual": actual,
            "raw": raw,
            "normalized": normalized,
            "handling": values.pop("handling", ""),
            "evidence": evidence,
            "message": message,
            "details": values,
        }
        return self._render_tool_line(event, level, message, known)

    def _render_tool_line(self, event: str, level: str, message: str, known: Mapping[str, Any]) -> str:
        """Render the compact, two-layer human ledger.

        Device/profile regexes are intentionally hidden here.  They are kept
        in the profile and the continuous serial log is the raw evidence.  The
        main ledger shows only the extracted ``KEY: VALUE`` fact; a judgement
        is rendered on the following line so device facts cannot be confused
        with a tool-derived PASS/FAIL decision.
        """
        event_name = str(event or "EVENT").upper()
        case_id = str(known.get("case_id") or "")
        position = self._case_positions.get(case_id)
        case_prefix = f"{position}/{self._planned_case_count or self._frozen_case_count}" if position else "-/-"
        metadata = self._case_metadata.get(case_id, {})
        raw = known.get("raw")
        raw_text = ""
        raw_items = raw if isinstance(raw, list) else []
        if isinstance(raw, str):
            raw_text = raw
            try:
                raw = json.loads(raw)
            except (TypeError, ValueError):
                pass
        if not isinstance(raw, Mapping):
            if raw_items and all(isinstance(item, Mapping) for item in raw_items):
                raw = {
                    str(item.get("tag_name")): item.get("raw_value")
                    for item in raw_items
                    if str(item.get("tag_name") or "").strip()
                }
            else:
                raw = {}
        normalized = known.get("normalized")
        if not isinstance(normalized, Mapping):
            normalized = {}
        details = known.get("details")
        if not isinstance(details, Mapping):
            details = {}

        def value(*names: str, default: Any = "") -> Any:
            for name in names:
                candidate = known.get(name)
                if candidate not in (None, "", [], {}):
                    return candidate
                candidate = details.get(name)
                if candidate not in (None, "", [], {}):
                    return candidate
                candidate = raw.get(name)
                if candidate not in (None, "", [], {}):
                    return candidate
            return default

        def inline(value_to_render: Any) -> str:
            return self._text(value_to_render)

        def suffix(*pairs: tuple[str, Any]) -> str:
            return " ".join(f"{name}={inline(item)}" for name, item in pairs if item not in (None, "", [], {}))

        def fact(tag: str, key: str, value_to_render: Any, *extra: tuple[str, Any]) -> str:
            line = f"{key}: {inline(value_to_render)}"
            tail = suffix(*extra)
            if tail:
                line += f" {tail}"
            return f"{known['time']} [{tag}] {line}\n"

        def judgement(tag: str, name: str, status: Any, *extra: tuple[str, Any]) -> str:
            line = f"判定: {name}={inline(status)}"
            tail = suffix(*extra)
            if tail:
                line += f" {tail}"
            return f"{known['time']} [{tag}] {line}\n"

        def raw_value(*names: str, default: Any = "") -> Any:
            for name in names:
                candidate = raw.get(name)
                if candidate not in (None, "", [], {}):
                    return candidate
                candidate = value(name)
                if candidate not in (None, "", [], {}):
                    return candidate
            return default

        def judgement_status(default: Any = "") -> Any:
            return value("tool_status", "wakeup_status", "command_status", "online_status", "player_status", "status", default=default)

        if event_name == "FIXED_FACT":
            key = str(value("fact_key", default="DEVICE")).upper()
