        if event_name.startswith("SERIAL_COMMAND") or event_name.startswith("PROFILE_RECOVERY"):
            if event_name == "PROFILE_RECOVERY_CANCELLED":
                return judgement("RESULT", "重启恢复", "CANCELLED", ("原因", known.get("reason", "")))
